#!/usr/bin/env python3
"""List every table method of include/xip.h whose arguments are pointers or structs, and every struct that
contains a pointer. Output is Markdown (modules/ABI-POINTERS.md). Usage: scripts/abi-pointers.py > modules/ABI-POINTERS.md"""
import re, sys, pathlib
src = pathlib.Path(__file__).resolve().parent.parent.joinpath("include/xip.h").read_text()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)
structs = {}
for m in re.finditer(r"typedef struct(?:\s+\w+)?\s*\{(.*?)\}\s*(\w+)\s*;", src, flags=re.S):
    structs[m.group(2)] = m.group(1)
tables = {}
for name, body in structs.items():
    fns = re.findall(r"([\w \*]+?)\(\*(\w+)\)\s*\((.*?)\)\s*;", body, flags=re.S)
    if fns:
        tables[name] = fns
def split(args):
    out, depth, cur = [], 0, ""
    for ch in args:
        if ch == "(": depth += 1
        if ch == ")": depth -= 1
        if ch == "," and depth == 0: out.append(cur.strip()); cur = ""
        else: cur += ch
    if cur.strip(): out.append(cur.strip())
    return out
def kind(a):
    a = " ".join(a.split())
    if a in ("void", ""): return None
    if "*" not in a: return None
    if re.search(r"\bxip_\w+\s*\*", a) and "xip_host" not in a: return ("struct*", a)
    if re.search(r"\b(uint8_t|char|void)\s*\*\*", a): return ("out-pointer", a)
    if re.search(r"\b(uint8_t|char)\s*\*", a): return ("buffer", a)
    if re.search(r"\bvoid\s*\*", a) and "ctx" in a or "user" in a or "owner" in a: return None
    return ("scalar-out", a)
ptr_fields = {}
for name, body in structs.items():
    for line in body.split(";"):
        if "(*" in line: continue
        if "*" in line and line.strip(): ptr_fields.setdefault(name, []).append(" ".join(line.split()))
print("# Pointers in the table ABI\n")
print("Generated by `scripts/abi-pointers.py` from `include/xip.h`. Direction: a call that crosses the module/host boundary")
print("must not depend on shared memory or pointers (binder model: a CBOR record or a pool packet, or a pointer-free")
print("fixed struct). Every row below breaks that and is a candidate to change. Kinds: `struct*` = pointer to a C struct")
print("(layout and any pointer inside it become ABI); `buffer` = caller bytes (`uint8_t *`, `char *`), should become a packet or")
print("a record; `out-pointer` = host returns a pointer into its own memory; `scalar-out` = small out parameter, returnable as a")
print("pointer-free result record.\n")
total = 0
for t, fns in tables.items():
    rows = []
    for ret, name, args in fns:
        ks = [k for k in (kind(a) for a in split(args)) if k]
        rp = "*" in ret
        if ks or rp:
            rows.append((name, ret.strip(), ks, rp))
    if not rows: continue
    print(f"## `{t}`\n")
    print("| method | flags | pointer arguments |\n|---|---|---|")
    for name, ret, ks, rp in rows:
        flags = sorted({k[0] for k in ks} | ({"returns-pointer"} if rp else set()))
        print(f"| `{name}` | {', '.join(flags)} | " + "; ".join(f"`{k[1]}`" for k in ks) + (f"; returns `{ret}`" if rp else "") + " |")
        total += 1
    print()
print("## Structs that contain pointers\n")
for n, fs in sorted(ptr_fields.items()):
    if n in tables and all("(*" in l for l in structs[n].split(";") if l.strip()): continue
    print(f"* `{n}`: " + "; ".join(f"`{f}`" for f in fs))
print(f"\n{total} table methods flagged.", file=sys.stderr)
