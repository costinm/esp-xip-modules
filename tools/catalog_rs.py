#!/usr/bin/env python3
"""Turn the console's generated C tables (catalog.h from `mesh-api-gen --out-console-catalog`, native.h from `--out-console-native`) into Rust
constants for modules/mod_con, until mesh-api-gen writes Rust for them itself. Only integers: a module image has no relocations.

    catalog_rs.py catalog.h native.h > src/tables.rs
"""
import re
import sys

TYPES = {"uint8_t": "u8", "uint16_t": "u16", "uint32_t": "u32", "int8_t": "i8", "int16_t": "i16", "int32_t": "i32", "char": "u8"}


def camel(name):
    return "".join(p.capitalize() for p in name.split("_"))


def convert(path):
    text = open(path).read()
    out = []
    structs = {}
    for m in re.finditer(r"typedef struct \{([^}]*)\} (\w+);", text):
        fields = []
        for stmt in m.group(1).split(";"):
            stmt = stmt.strip()
            if not stmt:
                continue
            ctype, names = stmt.split(None, 1)
            fields += [(n.strip(), TYPES[ctype]) for n in names.split(",")]
        structs[m.group(2)] = fields
        out.append("#[derive(Clone, Copy)]\npub struct %s {\n%s}\n" % (camel(m.group(2)), "".join("    pub %s: %s,\n" % f for f in fields)))
    for m in re.finditer(r"#define (CAT_\w+|NAT_\w+) (\d+)", text):
        if not m.group(1).startswith(("CAT_K_", "NAT_K_")) and m.group(1) not in ("NAT_CTX", "NAT_IN", "NAT_OUT"):
            out.append("pub const %s_N: usize = %s;\n" % (m.group(1), m.group(2)))
        else:
            out.append("pub const %s: u16 = %s;\n" % (m.group(1), m.group(2)))
    for m in re.finditer(r"static const (\w+) (\w+)\[[^\]]*\] = \{(.*)\};", text):
        ctype, name, body = m.groups()
        if ctype in TYPES:
            vals = [v.strip() for v in body.split(",") if v.strip()]
            out.append("pub static %s: [u8; %d] = [%s];\n" % (name.upper(), len(vals), ", ".join(vals)))
            continue
        fields = structs[ctype]
        entries = re.findall(r"\{([^{}]*)\}", body)
        rows = []
        for e in entries:
            vals = [v.strip() for v in e.split(",")]
            rows.append("%s { %s }" % (camel(ctype), ", ".join("%s: %s" % (f[0], v) for f, v in zip(fields, vals))))
        out.append("pub static %s: [%s; %d] = [\n    %s,\n];\n" % (name.upper(), camel(ctype), len(rows), ",\n    ".join(rows)))
    return out


def main():
    print("// GENERATED by tools/catalog_rs.py from %s. Do not edit." % ", ".join(a.split("/")[-1] for a in sys.argv[1:]))
    print("#![allow(dead_code)]\n")
    for path in sys.argv[1:]:
        print("".join(convert(path)))


main()
