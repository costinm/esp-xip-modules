#!/usr/bin/env python3
"""Generate the module ABI from abi/API.md (the format of the ssh-mesh and DMesh API.md files).

  gen_abi.py            write include/espmod.h and the Rust mirror (crates/espmod-abi)
  gen_abi.py --check    fail if those files are stale or a released slot changed (CI)
  gen_abi.py --update-lock   record the current table as abi/espmod.lock (at a release)
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from apimd import num, prose, sections, sections_top, tables, top_text  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "abi", "API.md")
LOCK = os.path.join(ROOT, "abi", "espmod.lock")
HEADER = os.path.join(ROOT, "include", "espmod.h")
RUST = os.path.join(ROOT, "crates", "espmod-abi", "src", "generated.rs")

SIZES32 = {"uint8_t": 1, "uint16_t": 2, "uint32_t": 4, "int32_t": 4, "uint64_t": 8, "size_t": 4, "const uint8_t *": 4}


def load():
    with open(SRC) as f:
        text = f.read()
    meta = dict(kv.split("=") for kv in re.search(r"<!-- espmod-abi: (.*?) -->", text).group(1).split())
    d = {"abi": {"version": int(meta["version"]), "prefix": meta["prefix"], "released": meta["released"] == "true"},
         "error": [], "constants": [], "struct": [], "entry": []}
    top = {h: body for h, body in sections_top(text)}
    for name, value, doc in tables(top["Results"]):
        d["error"].append({"name": name, "value": num(value), "doc": doc})
    for heading, body in sections(top_text(text, "Constants"), 2):
        group = re.match(r"`(\w+)`", heading).group(1)
        items = [[n, num(v), doc] for n, v, doc in tables(body)]
        d["constants"].append({"group": group, "doc": prose(body) or heading, "items": items})
    for heading, body in sections(top_text(text, "Types"), 2):
        name = re.match(r"`(\w+)`", heading).group(1)
        fields = []
        for fname, ftype, fdoc in tables(body):
            m = re.match(r"(.*)\[(\d+)\]$", ftype)
            fields.append([m.group(1), f"{fname}[{m.group(2)}]", fdoc] if m else [ftype, fname, fdoc])
        text_ = prose(body)
        st = {"name": name, "doc": heading.split("—", 1)[-1].strip() if "—" in heading else name, "fields": fields}
        if "Packed." in text_:
            st["packed"] = True
        d["struct"].append(st)
    entries = []
    for heading, body in sections(top_text(text, "Host calls"), 2):
        m = re.match(r"(\d+)\. `(\w+)` — (.*)", heading)
        returns = re.search(r"\*\*Returns:\*\* `([^`]+)` — (.*)", "\n".join(body))
        args = []
        for aname, atype, _ in tables(body):
            args.append(f"{atype}{'' if atype.endswith('*') else ' '}{aname}")
        entries.append((int(m.group(1)), {"name": m.group(2), "ret": returns.group(1), "args": args,
                                           "doc": m.group(3).strip(), "returns": returns.group(2).strip(),
                                           "detail": prose(body)}))
    entries.sort(key=lambda e: e[0])
    assert [n for n, _ in entries] == list(range(1, len(entries) + 1)), "host calls must be numbered 1..N without gaps"
    d["entry"] = [e for _, e in entries]
    return d


def decl(ret, name, args):
    """C declaration of one function pointer; `void *user` is always first."""
    return f"{ret} (*{name})(void *user{''.join(', ' + a for a in args)})"


def signature(e):
    return f"{e['ret']} {e['name']}({', '.join(e['args'])})"


def array_split(field):
    m = re.match(r"(\w+)\[(\d+)\]$", field)
    return (m.group(1), int(m.group(2))) if m else (field, None)


def struct_size32(st):
    total = 0
    for typ, name, _ in st["fields"]:
        _, n = array_split(name)
        total += SIZES32[typ] * (n or 1)
    return total


def header(d):
    abi, P = d["abi"], d["abi"]["prefix"].upper()
    o = ["/* GENERATED by tools/gen_abi.py from abi/API.md. Do not edit. */",
         "#pragma once", "", "#include <stddef.h>", "#include <stdint.h>", "",
         "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
         f"#define {P}_ABI_VERSION {abi['version']}u", "", "/* Results: 0 or positive on success, negative on error. */", "enum {"]
    for e in d["error"]:
        o.append(f"    {P}_{e['name']} = {e['value']}, /* {e['doc']} */")
    o += ["};", ""]
    for g in d["constants"]:
        o.append(f"/* {g['doc']} */")
        for name, value, doc in g["items"]:
            v = f"0x{value:x}u" if value > 255 else str(value)
            o.append(f"#define {P}_{g['group']}_{name} {v}" + (f" /* {doc} */" if doc else ""))
        o.append("")
    for st in d["struct"]:
        tname = f"{abi['prefix']}_{st['name']}"
        o.append(f"/* {st['doc']} */")
        o.append(f"typedef struct{' __attribute__((packed))' if st.get('packed') else ''} {tname} {{")
        for typ, name, doc in st["fields"]:
            o.append(f"    {typ} {name};" + (f" /* {doc} */" if doc else ""))
        o.append(f"}} {tname};")
        if any("*" in t for t, _, _ in st["fields"]):   # pointer sizes differ on a development host
            o.append(f"#if UINTPTR_MAX == 0xffffffffu\n_Static_assert(sizeof({tname}) == {struct_size32(st)}, \"{tname} layout\");\n#endif")
        else:
            o.append(f"_Static_assert(sizeof({tname}) == {struct_size32(st)}, \"{tname} layout\");")
        o.append("")
    n = len(d["entry"])
    o += ["/* The host table. The module receives it in espmod_entry() and keeps nothing from it after returning.",
          " * Every slot is always filled; a feature the host lacks returns ESPMOD_ERR_UNSUPPORTED. */",
          f"typedef struct {abi['prefix']}_host {{",
          f"    uint32_t abi_version; /* {P}_ABI_VERSION of the host */",
          "    uint32_t size;        /* sizeof of the host's table: slots beyond it do not exist */",
          f"    uint32_t features;    /* {P}_FEAT_* */",
          "    void *user;           /* first argument of every call */"]
    for i, e in enumerate(d["entry"]):
        o.append(f"    {decl(e['ret'], e['name'], e['args'])}; /* slot {i}: {e['doc'].split('. ')[0].rstrip('.')} */")
    o += [f"}} {abi['prefix']}_host;", "",
          "#if UINTPTR_MAX == 0xffffffffu",
          f"_Static_assert(sizeof({abi['prefix']}_host) == {16 + 4 * n}, \"{abi['prefix']}_host layout\");",
          "#endif", "",
          "/* Non-zero when the host's table includes this call (older hosts are shorter). */",
          f"#define {P}_HOST_HAS(host, call) \\",
          f"    ((host)->size >= offsetof({abi['prefix']}_host, call) + sizeof((host)->call))", "",
          "/* The one symbol a module exports. The host calls it for every event (docs: abi/API.md, Model):",
          " * call->component == ESPMOD_HOST_COMPONENT is the host's own (START, STOP, ...). `state` is the module's",
          " * zeroed state block. Return ESPMOD_RET_CONTINUE, ESPMOD_RET_DONE or a negative error. */",
          f"typedef int (*{abi['prefix']}_handle_fn)(const {abi['prefix']}_host *host, void *state,",
          f"                                          const {abi['prefix']}_call *call);",
          f"int {abi['prefix']}_handle(const {abi['prefix']}_host *host, void *state, const {abi['prefix']}_call *call);",
          "", "#ifdef __cplusplus", "}", "#endif", ""]
    return "\n".join(o)


RUST_TYPES = {"int": "i32", "uint8_t": "u8", "uint16_t": "u16", "uint32_t": "u32", "int32_t": "i32", "uint64_t": "u64",
              "size_t": "usize", "void": "()"}


def rust_type(ctype, prefix):
    """Map a C type spelling from the table ('const uint8_t *', 'size_t *', 'espmod_event *') to Rust."""
    t = ctype.strip()
    const = t.startswith("const ")
    t = t.removeprefix("const ").strip()
    ptr = t.endswith("*")
    t = t.rstrip("*").strip()
    if t == "void":
        base = "u8" if ptr else "()"
    elif t.startswith(prefix + "_"):
        base = "".join(w.capitalize() for w in t[len(prefix) + 1:].split("_"))
    else:
        base = RUST_TYPES[t]
    if not ptr:
        return base
    return f"*{'const' if const else 'mut'} {base}"


def split_arg(arg):
    m = re.match(r"(.*?)(\w+)$", arg.strip())
    return m.group(1).strip(), m.group(2)


def camel(name):
    return "".join(w.capitalize() for w in name.split("_"))


def rust(d):
    abi, P, pre = d["abi"], d["abi"]["prefix"].upper(), d["abi"]["prefix"]
    o = ["// GENERATED by tools/gen_abi.py from abi/API.md. Do not edit.",
         "#![allow(clippy::too_many_arguments)]", "", "use core::ffi::c_void;", "",
         f"pub const ABI_VERSION: u32 = {abi['version']};", ""]
    for e in d["error"]:
        o.append(f"/// {e['doc']}")
        o.append(f"pub const {e['name'].removeprefix('ERR_') if e['name'] != 'OK' else 'OK'}: i32 = {e['value']};" if False else
                 f"pub const {('ERR_' + e['name'].removeprefix('ERR_')) if e['name'] != 'OK' else 'OK'}: i32 = {e['value']};")
    o.append("")
    for g in d["constants"]:
        o.append(f"// {g['group']}: {g['doc']}")
        for name, value, text in g["items"]:
            o.append(f"pub const {g['group']}_{name}: u32 = {value};" + (f" // {text}" if text else ""))
        o.append("")
    for st in d["struct"]:
        o.append(f"/// {st['doc']}")
        o.append("#[repr(C, packed)]" if st.get("packed") else "#[repr(C)]")
        ptr = any("*" in t for t, _, _ in st["fields"])
        o.append("#[derive(Clone, Copy, Default)]" if not st.get("packed") and not ptr else "#[derive(Clone, Copy)]")
        o.append(f"pub struct {camel(st['name'])} {{")
        for typ, name, text in st["fields"]:
            base, n = array_split(name)
            rt = RUST_TYPES.get(typ) or rust_type(typ, pre)
            o.append(f"    pub {base}: {f'[{rt}; {n}]' if n else rt}, // {text}")
        o.append("}")
        o.append(f"#[cfg(target_pointer_width = \"32\")]\nconst _: () = assert!(core::mem::size_of::<{camel(st['name'])}>() == {struct_size32(st)});")
        o.append("")
    o += ["/// The host table (see abi/API.md). Slots are `None` only if a host leaves one empty; slots past `size` do not exist.",
          "#[repr(C)]", "pub struct Host {", "    pub abi_version: u32,", "    pub size: u32,", "    pub features: u32,",
          "    pub user: *mut c_void,"]
    for e in d["entry"]:
        args = ["user: *mut c_void"]
        for a in e["args"]:
            ct, nm = split_arg(a)
            args.append(f"{'r#type' if nm == 'type' else nm}: {rust_type(ct, pre)}")
        ret = e["ret"].strip()
        r = "" if ret == "void" else f" -> {'*mut u8' if ret == 'void *' else rust_type(ret, pre)}"
        o.append(f"    /// {e['doc']}")
        o.append(f"    pub {e['name']}: Option<unsafe extern \"C\" fn({', '.join(args)}){r}>,")
    o.append("}")
    o.append(f"#[cfg(target_pointer_width = \"32\")]\nconst _: () = assert!(core::mem::size_of::<Host>() == {16 + 4 * len(d['entry'])});")
    o.append("")
    o.append("/// Byte offset of each host call, for `Host::has`.")
    o.append("pub mod slot {")
    for i, e in enumerate(d["entry"]):
        o.append(f"    pub const {e['name'].upper()}: usize = {16 + 4 * i};")
    o.append("}")
    return "\n".join(o) + "\n"


def lock_data(d):
    return {"abi_version": d["abi"]["version"],
            "entries": [signature(e) for e in d["entry"]],
            "structs": {s["name"]: [f"{t} {n}" for t, n, _ in s["fields"]] for s in d["struct"]}}


def lock_problems(d, lock):
    cur = lock_data(d)
    bad = []
    for i, sig in enumerate(lock["entries"]):
        if i >= len(cur["entries"]):
            bad.append(f"slot {i} removed: {sig}")
        elif cur["entries"][i] != sig:
            bad.append(f"slot {i} changed: {sig} -> {cur['entries'][i]}")
    for name, fields in lock["structs"].items():
        now = cur["structs"].get(name)
        if now is None or now[:len(fields)] != fields:
            bad.append(f"struct {name} changed or removed")
    return bad


def main():
    d = load()
    outputs = {HEADER: header(d).replace("`", ""), RUST: rust(d)}
    if "--update-lock" in sys.argv:
        with open(LOCK, "w") as f:
            json.dump(lock_data(d), f, indent=1)
            f.write("\n")
        print(f"wrote {LOCK}")
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not os.path.exists(p) or open(p).read() != text]
        if stale:
            sys.exit("stale (run tools/gen_abi.py): " + ", ".join(os.path.relpath(p, ROOT) for p in stale))
        if os.path.exists(LOCK):
            problems = lock_problems(d, json.load(open(LOCK)))
            if problems:
                msg = "\n".join(problems)
                if d["abi"].get("released"):
                    sys.exit("released ABI changed:\n" + msg)
                print("note: abi/espmod.lock differs (ABI not released yet):\n" + msg)
        print("abi ok")
        return
    for path, text in outputs.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
