#!/usr/bin/env python3
"""Generate the method and field catalog of the console module from the API.md files of main and the modules.

  gen_catalog.py            write modules/mod_console/catalog.h
  gen_catalog.py --check    fail if it is stale (CI)

The catalog is integers and one string pool (no pointers: a flash module has no relocations). It names the
components, methods and fields so a typed line becomes tagged CBOR and an answer becomes text.
"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from apimd import module_api, module_types  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "modules", "mod_console", "catalog.h")
TWINS = {"mod_rtest"}   # same component and methods as mod_test (installed in the same slot): listed once
SOURCES = sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, "modules", "*", "API.md"))
                 if os.path.basename(os.path.dirname(p)) not in TWINS)

K = {"any": 0, "text": 1, "bool": 2, "uint": 3, "int": 4, "bytes": 5, "map": 6, "array": 7}


def kind_of(typ, records):
    """(kind, record index + 1 or 0) of a type column."""
    array = typ.endswith("[]")
    name = typ[:-2] if array else typ
    if name in records:
        return (K["array"] if array else K["map"]), records[name] + 1
    if array or name == "array":
        return K["array"], 0
    base = {"string": "text", "text": "text", "bool": "bool", "bytes": "bytes", "hex": "bytes", "map": "map",
            "int": "int", "i8": "int", "i16": "int", "i32": "int", "i64": "int"}.get(name)
    if base:
        return K[base], 0
    return (K["uint"] if name.startswith("u") or name == "enum" else K["any"]), 0


def build():
    comps, types = [], {}
    for rel in SOURCES:
        text = open(os.path.join(ROOT, rel)).read()
        comps += module_api(text)
        types.update(module_types(text))
    pool, offsets = bytearray(b"\0"), {}

    def name(s):
        if s not in offsets:
            offsets[s] = len(pool)
            pool.extend(s.encode() + b"\0")
        return offsets[s]

    fields, records = [], {}
    names = sorted(types)
    for i, t in enumerate(names):
        records[t] = i
    rec_rows = []
    for t in names:
        first = len(fields)
        for tag, fname, ftype in types[t]:
            k, r = kind_of(ftype, records)
            fields.append((name(fname), tag, k, r))
        rec_rows.append((name(t), first, len(fields) - first))
    method_rows, comp_rows = [], []
    for cname, cid, methods in comps:
        first = len(method_rows)
        for mname, mid, _summary, req, resp in methods:
            rf = len(fields)
            for tag, fname, ftype in req:
                k, r = kind_of(ftype, records)
                fields.append((name(fname), tag, k, r))
            pf = len(fields)
            for tag, fname, ftype in resp:
                k, r = kind_of(ftype, records)
                fields.append((name(fname), tag, k, r))
            method_rows.append((name(mname), mid, rf, pf - rf, pf, len(fields) - pf))
        comp_rows.append((name(cname), cid, first, len(method_rows) - first))
    o = ["/* GENERATED by tools/gen_catalog.py from " + ", ".join(SOURCES) + ". Do not edit. */", "#pragma once", "",
         "#include <stdint.h>", "",
         "#define CAT_K_ANY 0\n#define CAT_K_TEXT 1\n#define CAT_K_BOOL 2\n#define CAT_K_UINT 3\n#define CAT_K_INT 4\n"
         "#define CAT_K_BYTES 5\n#define CAT_K_MAP 6\n#define CAT_K_ARRAY 7", "",
         "/* names: NUL-terminated strings, 16-bit offsets into this pool */"]
    chunk = ", ".join(f"0x{b:02x}" for b in pool)
    o.append(f"static const uint8_t cat_pool[{len(pool)}] = {{{chunk}}};")
    o.append("typedef struct { uint16_t name, id, first, count; } cat_comp;             /* methods [first, first+count) */")
    o.append("typedef struct { uint16_t name, id, req, nreq, resp, nresp; } cat_method; /* fields of cat_fields */")
    o.append("typedef struct { uint16_t name, tag; uint8_t kind, record; } cat_field;     /* record: 1 + index in cat_records */")
    o.append("typedef struct { uint16_t name, first, count; } cat_record;")
    o.append(f"#define CAT_COMPS {len(comp_rows)}\n#define CAT_METHODS {len(method_rows)}\n#define CAT_FIELDS {len(fields)}\n#define CAT_RECORDS {len(rec_rows)}")
    o.append("static const cat_comp cat_comps[CAT_COMPS] = {" + ", ".join("{%d,%d,%d,%d}" % r for r in comp_rows) + "};")
    o.append("static const cat_method cat_methods[CAT_METHODS + 1] = {" + ", ".join("{%d,%d,%d,%d,%d,%d}" % r for r in method_rows) + ", {0,0,0,0,0,0}};")
    o.append("static const cat_field cat_fields[CAT_FIELDS + 1] = {" + ", ".join("{%d,%d,%d,%d}" % r for r in fields) + ", {0,0,0,0}};")
    o.append("static const cat_record cat_records[CAT_RECORDS + 1] = {" + ", ".join("{%d,%d,%d}" % r for r in rec_rows) + ", {0,0,0}};")
    return "\n".join(o) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("stale (run tools/gen_catalog.py): modules/mod_console/catalog.h")
        print("catalog ok")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote modules/mod_console/catalog.h")


if __name__ == "__main__":
    main()
