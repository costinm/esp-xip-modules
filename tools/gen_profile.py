#!/usr/bin/env python3
"""Generate the portable bearer field codec from the host ABI's API.md."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'crates/xip-abi/src/profile/generated.rs'
C_OUT = ROOT / 'include/xip_transport.h'

def generate():
    source = (ROOT / 'abi/API.md').read_text()
    rules = dict((name, (rule, field)) for name, rule, field in re.findall(
        r'^\| `(\w+)` \| `(\w+)` \| `(\w+)` \|$', source, re.M))
    section = source.split('# `transport` API (1)\n', 1)[1]
    fields = [(int(tag), name, typ, *rules[name]) for tag, name, typ in re.findall(
        r'^\| (\d+) \| `(\w+)` \| `(\w+)` \|', section, re.M) if name != 'mode']
    types = {'string': "&'a [u8]", 'u8': 'u8', 'u32': 'u32', 'i32': 'i32', 'bool': 'bool'}
    out = ['// GENERATED by tools/gen_profile.py from abi/API.md. Do not edit.',
           'use super::{cbor::{Decoder, Encoder}, TransportProfile};',
           '/// Shared with DMesh control::TransportConfig and platform_api::TransportSetRequest',
           '/// (crates/dmesh-server/src). Same transport fields and tagged-CBOR representation;',
           '/// keep both sides in sync through the common abi/API.md schema.',
           '#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]',
           "pub struct TransportConfig<'a> {"]
    for _, name, typ, rule, _ in fields:
        rt = '[u8; 6]' if rule == 'mac' else types[typ]
        out.append(f'    pub {name}: Option<{rt}>,')
    out += ['}', 'pub fn field_count(config: TransportConfig<\'_>) -> u64 {',
            '    [' + ', '.join(f'config.{name}.is_some()' for _, name, *_ in fields) + ']',
            '        .into_iter().filter(|v| *v).count() as u64', '}',
            'pub fn validate_config(config: TransportConfig<\'_>) -> Option<()> {']
    for _, name, _, rule, _ in fields:
        out.append(f'    if let Some(value) = config.{name} {{ super::valid_{rule}(value)?; }}')
    out += ['    Some(())', '}',
            'pub fn decode_config(encoded: &[u8]) -> Option<TransportConfig<\'_>> {',
            '    let mut d = Decoder::new(encoded);',
            '    let (major, count) = d.head()?;',
            '    if major != 5 || count == u64::MAX { return None; }',
            '    let mut config = TransportConfig::default();',
            '    let mut seen = 0u64;',
            '    for _ in 0..count {', '        let key = d.uint()?;',
            '        if key < 64 { let bit = 1u64 << key; if seen & bit != 0 { return None; } seen |= bit; }',
            '        match key {']
    for tag, name, typ, rule, _ in fields:
        read = ('super::read_mac(&mut d)?' if rule == 'mac' else
                'super::read_bytes(&mut d)?' if typ == 'string' else
                'd.boolean()?' if typ == 'bool' else
                f'{types[typ]}::try_from(d.int()?).ok()?' if typ == 'i32' else
                f'{types[typ]}::try_from(d.uint()?).ok()?')
        out.append(f'            {tag} => config.{name} = Some({read}),')
    out += ['            _ => d.skip()?,', '        }', '    }',
            '    if !d.is_finished() { return None; }', '    validate_config(config)?;',
            '    Some(config)', '}',
            'pub fn encode_config_into(config: TransportConfig<\'_>, e: &mut Encoder<\'_>) -> Option<()> {',
            '    validate_config(config)?;']
    for tag, name, typ, rule, _ in fields:
        write = ('e.bytes_value(&value)?' if rule == 'mac' else
                 'e.text_value(value)?' if typ == 'string' else
                 'e.boolean(value)?' if typ == 'bool' else
                 'e.int(i64::from(value))?' if typ == 'i32' else
                 'e.uint(u64::from(value))?')
        out.append(f'    if let Some(value) = config.{name} {{ e.uint({tag})?; {write}; }}')
    out += ['    Some(())', '}',
            'pub fn apply_config(config: TransportConfig<\'_>, profile: &mut TransportProfile) -> Option<()> {', '    validate_config(config)?;']
    for _, name, typ, rule, field in fields:
        if field in ('wake_target', 'iface'):
            continue
        if rule == 'mac':
            assign = f'profile.{field} = value; profile.{field}_set = true;'
        elif typ == 'string':
            assign = f'profile.{field}.fill(0); profile.{field}[..value.len()].copy_from_slice(value); profile.{field}_len = value.len();'
        else:
            assign = f'profile.{field} = value;'
        out.append(f'    if let Some(value) = config.{name} {{ {assign} }}')
    out += ['    if let Some(selector) = config.uart {',
            '        profile.uart = super::normalize_uart_selector(selector).unwrap_or(profile.uart);',
            '        if config.uart_mode.is_none() { profile.uart_mode = if selector == super::UART_OFF { 0 } else { 2 }; }',
            '        if config.uart_baud.is_none() { profile.uart_baud = super::uart_baud(selector); }',
            '    }', '    Some(())', '}', 'impl TransportProfile {',
            '    pub fn config(&self) -> Option<TransportConfig<\'_>> {',
            '        if self.ssid_len > 32 || self.sta_passphrase_len > 63 || self.ap_ssid_len > 32 || self.ap_passphrase_len > 63 { return None; }',
            '        let config = TransportConfig {']
    for _, name, typ, rule, field in fields:
        value = ('None' if field in ('wake_target', 'iface') else
                 f'self.{field}_set.then_some(self.{field})' if rule == 'mac' else
                 f'(self.{field}_len != 0).then_some(&self.{field}[..self.{field}_len])' if typ == 'string' else
                 f'Some(self.{field})')
        # Zero channel means automatic selection; omit it on the wire.
        if name == 'channel': value = '(self.sta_channel != 0).then_some(self.sta_channel)'
        out.append(f'            {name}: {value},')
    out += ['        };', '        validate_config(config)?;', '        Some(config)', '    }', '}']
    from gen_abi import load, array_split
    abi = next(st for st in load()['struct'] if st['name'] == 'bearer_profile')
    flags = {name for _, name, typ, _, _ in fields if typ == 'bool'} | {'sta_bssid_set', 'run_requested'}
    out += ['impl TransportProfile {',
            '    pub fn to_abi(&self) -> Option<crate::BearerProfile> {',
            '        self.config()?;', '        Some(crate::BearerProfile {']
    for _, name, _ in abi['fields']:
        name, _ = array_split(name)
        value = ('core::mem::size_of::<crate::BearerProfile>() as u32' if name == 'size' else
                 '1' if name == 'version' else 'u32::from(super::mode(self.requested_transport))' if name == 'mode' else
                 f'u8::from(self.{name})' if name in flags else
                 f'self.{name} as u32' if name.endswith('_len') else f'self.{name}')
        out.append(f'            {name}: {value},')
    out += ['        })', '    }',
            '    pub fn from_abi(value: &crate::BearerProfile) -> Option<Self> {',
            '        if value.version != 1 || value.size < core::mem::size_of::<crate::BearerProfile>() as u32 { return None; }',
            '        let kind = super::transport_kind(u64::from(value.mode))?;']
    for name in sorted(flags):
        if any(array_split(f[1])[0] == name for f in abi['fields']):
            out.append(f'        if value.{name} > 1 {{ return None; }}')
    out += ['        let profile = Self {']
    for _, name, _ in abi['fields']:
        name, _ = array_split(name)
        if name in ('size', 'version'): continue
        target = 'requested_transport' if name == 'mode' else name
        value = ('(kind != super::TransportKind::Off).then_some(kind)' if name == 'mode' else
                 f'value.{name} != 0' if name in flags else
                 f'value.{name} as usize' if name.endswith('_len') else f'value.{name}')
        out.append(f'            {target}: {value},')
    out += ['        };', '        profile.config()?;', '        Some(profile)', '    }', '}']
    return '\n'.join(out) + '\n'

def run(check=False):
    text = generate()
    outputs = {OUT: text, C_OUT: generate_c()}
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'{path.name} is stale: run tools/gen_abi.py')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)

def generate_c():
    from gen_abi import load, array_split
    source = (ROOT / 'abi/API.md').read_text()
    rules = dict((name, (rule, field)) for name, rule, field in re.findall(
        r'^\| `(\w+)` \| `(\w+)` \| `(\w+)` \|$', source, re.M))
    section = source.split('# `transport` API (1)\n', 1)[1]
    fields = [(int(tag), name, typ, *rules[name]) for tag, name, typ in re.findall(
        r'^\| (\d+) \| `(\w+)` \| `(\w+)` \|', section, re.M) if name != 'mode' and rules[name][1] not in ('iface','wake_target')]
    abi = next(st for st in load()['struct'] if st['name'] == 'bearer_profile')
    predicates = {
        'bool':'{v} <= 1', 'u32':'1', 'channel':'{v} >= 1 && {v} <= 14',
        'rate':'{v} == 0 || {v} == 6 || {v} == 9 || {v} == 12 || {v} == 18 || {v} == 24 || {v} == 36 || {v} == 48 || {v} == 54',
        'dw':'{v} == 0 || {v} == 1 || {v} == 8 || {v} == 16', 'policy':'{v} <= 2',
        'enable':'{v} <= 1', 'uart':'{v} <= 9', 'baud':'{v} > 0 && {v} <= 5000000',
        'port':'{v} <= 3', 'power':'{v} >= -40 && {v} <= 30',
        'sf':'{v} == 0 || ({v} >= 5 && {v} <= 12)', 'cr':'{v} == 0 || ({v} >= 5 && {v} <= 8)',
    }
    out = ['/* GENERATED by tools/gen_profile.py from abi/API.md. */', '#pragma once',
           '#include "xip.h"', '#include "xip_cbor.h"', '#include <string.h>',
           'static inline void xip_transport_default(xip_bearer_profile *p) {',
           '    memset(p, 0, sizeof(*p)); p->size = sizeof(*p);']
    for typ, name, doc in abi['fields']:
        name, n = array_split(name)
        default = re.search(r'Default=(\d+)\.', doc)
        if default and not n and default.group(1) != '0': out.append(f'    p->{name} = {default.group(1)};')
    out += ['}', 'static inline void xip_transport_off(xip_bearer_profile *p) {',
            '    xip_transport_default(p); p->mode = 0; p->run_requested = 0; p->ap = 0; p->now = 2;',
            '    p->nan_dw_interval = 0; p->uart = 8; p->uart_mode = 0; p->ble = 0; p->radio_mode = 0;', '}',
            'static inline int xip_transport_validate(const xip_bearer_profile *p) {',
            '    if (!p || p->size < sizeof(*p) || p->version != 1) return -1;',
            '    if (p->mode != 0 && p->mode != 1 && p->mode != 5 && p->mode != 6) return -1;',
            '    if (p->run_requested > 1 || p->sta_bssid_set > 1) return -1;']
    for _, _, typ, rule, field in fields:
        if rule == 'mac': continue
        if typ == 'string':
            maximum = 32 if rule == 'ssid' else 63
            out.append(f'    if (p->{field}_len > {maximum} || memchr(p->{field}, 0, p->{field}_len)) return -1;')
            if rule == 'passphrase': out.append(f'    if (p->{field}_len && p->{field}_len < 8) return -1;')
        else:
            predicate = predicates[rule].format(v=f'p->{field}')
            if field == 'sta_channel': predicate = f'p->{field} == 0 || ({predicate})'
            out.append(f'    if (!({predicate})) return -1;')
    out += ['    return 0;', '}',
            'static inline int xip_transport_mac(const xip_cbor_item *v, uint8_t out[6]) {',
            '    if (v->type == XIP_CBOR_BYTES && v->n == 6) { memcpy(out, v->data, 6); return 0; }',
            '    if (v->type != XIP_CBOR_TEXT || v->n != 17) return -1;',
            '    for (unsigned i = 0; i < 6; ++i) {',
            '        if (i != 5 && v->data[i*3+2] != 58) return -1;',
            '        unsigned byte = 0;',
            '        for (unsigned j = 0; j < 2; ++j) { unsigned c = v->data[i*3+j];',
            '            unsigned n = c >= 48 && c <= 57 ? c-48 : c >= 65 && c <= 70 ? c-55 : c >= 97 && c <= 102 ? c-87 : 255;',
            '            if (n == 255) return -1;', '            byte = byte*16+n;', '        } out[i] = byte;',
            '    } return 0;', '}',
            'static inline int xip_transport_decode_fields(const uint8_t *data, size_t len, xip_bearer_profile *p) {',
            '    xip_bearer_profile candidate = *p; xip_bearer_profile *original = p; p = &candidate;', '    xip_cbor_r r = {data, len}; xip_cbor_item map, key, value; uint64_t seen = 0;',
            '    if (xip_cbor_next(&r, &map) || map.type != XIP_CBOR_MAP) return -1;',
            '    for (size_t i = 0; i < map.n; ++i) {',
            '        if (xip_cbor_next(&r, &key) || key.type != XIP_CBOR_UINT) return -1;',
            '        if (key.arg < 64) { uint64_t bit = (uint64_t)1 << key.arg; if (seen & bit) return -1; seen |= bit; }',
            '        xip_cbor_r saved = r;',
            '        if (xip_cbor_next(&r, &value)) return -1;', '        switch (key.arg) {',
            '        case 1: if (value.type != XIP_CBOR_UINT || (value.arg != 0 && value.arg != 1 && value.arg != 5 && value.arg != 6)) return -1;\n            p->mode = value.arg; break;']
    for tag, name, typ, rule, field in fields:
        out.append(f'        case {tag}:')
        if rule == 'mac':
            out += [f'            if (xip_transport_mac(&value, p->{field})) return -1;\n            p->{field}_set = 1; break;']
        elif typ == 'string':
            maxlen = 32 if rule == 'ssid' else 63
            minlen = 1 if rule == 'ssid' else 8
            out += [f'            if ((value.type != XIP_CBOR_TEXT && value.type != XIP_CBOR_BYTES) || value.n < {minlen} || value.n > {maxlen} || memchr(value.data, 0, value.n)) return -1;',
                    f'            memset(p->{field}, 0, sizeof(p->{field})); memcpy(p->{field}, value.data, value.n); p->{field}_len = value.n; break;']
        elif typ == 'bool':
            out.append(f'            if (value.type != XIP_CBOR_BOOL) return -1;\n            p->{field} = value.arg; break;')
        elif typ == 'i32':
            out.append(f'            {{ int64_t number; if (xip_cbor_as_int(&value, &number) || number < -40 || number > 30) return -1;\n            p->{field} = number; }} break;')
        else:
            maximum = 255 if typ == 'u8' else 4294967295
            predicate = predicates[rule].format(v='value.arg')
            out.append(f'            if (value.type != XIP_CBOR_UINT || value.arg > {maximum}u || !({predicate})) return -1;\n            p->{field} = value.arg; break;')
    out += ['        default: r = saved; if (xip_cbor_skip(&r)) return -1; break;', '        }', '    }',
            '    if ((seen & ((uint64_t)1 << 18)) && !(seen & ((uint64_t)1 << 28))) p->uart_mode = p->uart == 8 ? 0 : 2;',
            '    if ((seen & ((uint64_t)1 << 18)) && !(seen & ((uint64_t)1 << 29))) {',
            '        static const uint32_t baud[] = {115200,115200,9600,19200,38400,57600,230400,460800,115200,921600}; p->uart_baud = baud[p->uart];',
            '    }', '    if ((seen & ((uint64_t)1 << 18)) && p->uart == 0) p->uart = 1;',
            '    if (r.len || xip_transport_validate(p)) return -1;', '    *original = candidate; return 0;', '}',
            'static inline int xip_transport_encode(const xip_bearer_profile *p, xip_cbor_w *w) {',
            '    if (xip_transport_validate(p)) return -1;', '    size_t count = 1;']
    for _, _, typ, rule, field in fields:
        cond = (f'p->{field}_set' if rule == 'mac' else f'p->{field}_len != 0' if typ == 'string' else
                'p->sta_channel != 0' if field == 'sta_channel' else '1')
        out.append(f'    if ({cond}) ++count;')
    out += ['    xip_cbor_map(w, count); xip_cbor_uint(w, 1); xip_cbor_uint(w, p->mode);']
    for tag, _, typ, rule, field in fields:
        cond = (f'p->{field}_set' if rule == 'mac' else f'p->{field}_len != 0' if typ == 'string' else
                'p->sta_channel != 0' if field == 'sta_channel' else '1')
        writer = (f'xip_cbor_bytes(w, p->{field}, 6)' if rule == 'mac' else
                  f'xip_cbor_text(w, (const char *)p->{field}, p->{field}_len)' if typ == 'string' else
                  f'xip_cbor_bool(w, p->{field})' if typ == 'bool' else
                  f'xip_cbor_int(w, p->{field})' if typ == 'i32' else f'xip_cbor_uint(w, p->{field})')
        out.append(f'    if ({cond}) {{ xip_cbor_uint(w, {tag}); {writer}; }}')
    out += ['    return w->overflow ? -8 : 0;', '}',
            'static inline int xip_transport_apply_request(const uint8_t *data, size_t len, xip_bearer_profile *p) {',
            '    xip_cbor_r field; xip_cbor_item mode; int selected = -1;',
            '    if (!xip_cbor_get(data, len, 1, &field)) {',
            '        if (xip_cbor_next(&field, &mode) || mode.type != XIP_CBOR_UINT || (mode.arg != 0 && mode.arg != 1 && mode.arg != 5 && mode.arg != 6)) return -1;',
            '        selected = mode.arg; if (selected == 5) return -2;', '    }',
            '    /* Metadata needs a product hook; this minimal C owner has none. */',
            '    if (!xip_cbor_get(data, len, 25, &field) || !xip_cbor_get(data, len, 27, &field)) return -2;',
            '    int targeted = !xip_cbor_get(data, len, 2, &field) || !xip_cbor_get(data, len, 3, &field);',
            '    if (selected == 1 && !targeted && !p->ssid_len && !p->sta_bssid_set) return -1;',
            '    xip_bearer_profile candidate = *p;',
            '    if (selected == 0) xip_transport_off(&candidate);',
            '    if (selected == 1 && targeted) { memset(candidate.sta_passphrase, 0, sizeof(candidate.sta_passphrase)); candidate.sta_passphrase_len = 0; }',
            '    int rc = xip_transport_decode_fields(data, len, &candidate); if (rc) return rc;',
            '    if (selected >= 0) { candidate.mode = selected; candidate.run_requested = selected != 0; }',
            '    *p = candidate; return 0;', '}']
    out += ['static inline int xip_transport_equal(const xip_bearer_profile *a, const xip_bearer_profile *b) {']
    strings = {field for _, _, typ, rule, field in fields if typ == 'string' and rule != 'mac'}
    for _, name, _ in abi['fields']:
        name, size = array_split(name)
        if name in ('size', 'version') or any(name == field + '_len' for field in strings): continue
        if name in strings:
            out.append(f'    if (a->{name}_len != b->{name}_len || memcmp(a->{name}, b->{name}, a->{name}_len)) return 0;')
        elif name == 'sta_bssid':
            out.append('    if (a->sta_bssid_set && memcmp(a->sta_bssid, b->sta_bssid, 6)) return 0;')
        elif size:
            out.append(f'    if (memcmp(a->{name}, b->{name}, sizeof(a->{name}))) return 0;')
        else:
            out.append(f'    if (a->{name} != b->{name}) return 0;')
    out += ['    return 1;', '}']
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    run('--check' in sys.argv)
