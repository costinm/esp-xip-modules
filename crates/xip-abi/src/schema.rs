//! A compact schema of the component tables: for each component its methods, in table order, with their names and the shape of their
//! arguments. It is static data (`no_std`, no allocation) that every side can carry: the wasm bridge (`xip-wasm`) calls a native table
//! method from it without a `match` per method, a gateway or the console (`mod_system`) can turn a CBOR request into a call, and a proxy of the hardware over
//! a stream can name the methods it forwards (`modules/mod_wasm3/WASM-PORTING.md`).
//!
//! A component has no number: a caller finds it by name (`get_component`, or [`component`] for the tables the host provides), and a
//! method is its index in the table, whose order and version keep callers compatible. A module that hosts a table carries the schema of
//! it as a byte string and hands it to the runtime with the table (`Hw::provide_table`), so the runtime needs nothing compiled in.
//!
//! The byte string (generated by `mesh-api-gen --out-vtable-schema`, see `crates/mesh-api-gen/src/vtable.rs`) is, per method,
//! `name 0 note 0 nargs` and one tag per argument, and ends with a 0 byte. An argument is a word ([`Arg::Val`]: number, handle, packet), a
//! pointer-free C struct in or out (`In`/`Out`, the size), a string or bytes inline (`Str`, `Bytes`/`OutBytes`: the index of the argument
//! that is the length), or an array out (`OutArr`: element size, the index of the count). The context argument every table function takes
//! first is not listed. `note` flags what does not fit the parcel model cleanly, to be decided case by case.

include!("schema_data.rs");

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Arg {
    Val,
    In(usize),
    Out(usize),
    Str,
    Bytes(u8),
    OutBytes(u8),
    OutArr(usize, u8),
}

/// One method of a schema.
#[derive(Clone, Copy, Debug)]
pub struct Method<'a> {
    pub name: &'a str,
    /// Why the method needs a decision (empty when it fits).
    pub note: &'a str,
    nargs: usize,
    args: &'a [u8],
}

impl<'a> Method<'a> {
    pub fn nargs(&self) -> usize {
        self.nargs
    }
    /// The `i`-th argument after the context.
    pub fn arg(&self, i: usize) -> Option<Arg> {
        if i >= self.nargs {
            return None;
        }
        let mut at = 0;
        for _ in 0..i {
            at += width(self.args[at]);
        }
        let b = &self.args[at..];
        let size = || u16::from_le_bytes([b[1], b[2]]) as usize;
        Some(match b[0] {
            b'i' => Arg::In(size()),
            b'o' => Arg::Out(size()),
            b's' => Arg::Str,
            b'b' => Arg::Bytes(b[1]),
            b'B' => Arg::OutBytes(b[1]),
            b'a' => Arg::OutArr(size(), b[3]),
            _ => Arg::Val,
        })
    }
}

fn width(tag: u8) -> usize {
    match tag {
        b'i' | b'o' | b'b' | b'B' => if tag == b'i' || tag == b'o' { 3 } else { 2 },
        b'a' => 4,
        _ => 1,
    }
}

/// The methods of a schema, in table order.
pub fn methods(blob: &[u8]) -> impl Iterator<Item = Method<'_>> {
    let mut at = 0;
    core::iter::from_fn(move || {
        let name_end = at + blob.get(at..)?.iter().position(|b| *b == 0)?;
        if name_end == at {
            return None;
        }
        let note_start = name_end + 1;
        let note_end = note_start + blob.get(note_start..)?.iter().position(|b| *b == 0)?;
        let nargs = *blob.get(note_end + 1)? as usize;
        let args_start = note_end + 2;
        let mut end = args_start;
        for _ in 0..nargs {
            end += width(*blob.get(end)?);
        }
        let m = Method {
            name: core::str::from_utf8(&blob[at..name_end]).ok()?,
            note: core::str::from_utf8(&blob[note_start..note_end]).ok()?,
            nargs,
            args: blob.get(args_start..end)?,
        };
        at = end;
        Some(m)
    })
}

/// Method `index` of a schema.
pub fn method(blob: &[u8], index: usize) -> Option<Method<'_>> {
    methods(blob).nth(index)
}

/// A schema inside a larger block of memory (the address a module gave, up to the end of the memory): the bytes up to and with the end
/// marker, or empty when the block does not hold a well-formed schema.
pub fn trim(block: &[u8]) -> &[u8] {
    let mut len = 0;
    for m in methods(block) {
        len += m.name.len() + 1 + m.note.len() + 1 + 1 + m.args.len();
    }
    if block.get(len) == Some(&0) { &block[..=len] } else { &[] }
}

/// The schema of a component the host provides, by name.
pub fn component(name: &str) -> Option<&'static [u8]> {
    COMPONENTS.iter().find(|c| c.0 == name).map(|c| c.1)
}

/// The schema and the index of a method by names, for a caller that has only strings (a gateway, a proxy, the console).
pub fn find(component: &str, method: &str) -> Option<(&'static [u8], usize)> {
    let blob = self::component(component)?;
    Some((blob, methods(blob).position(|m| m.name == method)?))
}
